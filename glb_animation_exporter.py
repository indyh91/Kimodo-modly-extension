"""Animated GLTF/GLB writer adapter for conservative retarget clips."""

from __future__ import annotations

import base64
import copy
import importlib.util
import json
import math
import struct
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from retarget_errors import EXPORT_FAILED, RetargetError
from retargeting import RetargetClip
from rig_inspector import RigInspection


@dataclass(frozen=True)
class ExporterDependencyReport:
    pygltflib_available: bool
    gltflib_available: bool
    trimesh_available: bool

    @property
    def animated_skin_writer_confirmed(self) -> bool:
        return self.pygltflib_available or self.gltflib_available


def inspect_exporter_dependencies() -> ExporterDependencyReport:
    return ExporterDependencyReport(
        pygltflib_available=importlib.util.find_spec("pygltflib") is not None,
        gltflib_available=importlib.util.find_spec("gltflib") is not None,
        trimesh_available=importlib.util.find_spec("trimesh") is not None,
    )


class GlbAnimationExporter:
    """Append clip animation data while preserving the source glTF document.

    This deliberately supports the MVP seam only: translation plus bounded
    mapped-joint rotation channels generated by :func:`retargeting.build_retarget_clip`.
    It does not pretend to solve full arbitrary-rig retargeting; unsupported
    channel shapes fail closed.
    """

    clip_name = "Kimodo Motion"

    def write_animation(self, rig: RigInspection, clip: RetargetClip, output_path: Path) -> Path:
        output_path = Path(output_path)
        if output_path.suffix.lower() not in {".glb", ".gltf"}:
            raise RetargetError(EXPORT_FAILED, f"Animation output must be .glb or .gltf: {output_path}")
        if not clip.channels:
            raise RetargetError(EXPORT_FAILED, "Retarget clip contains no animation channels to write.")

        document, source_bin = _read_source_asset(rig.path)
        document = copy.deepcopy(document)
        bin_appender = _source_bin_appender(document, source_bin) if rig.path.suffix.lower() == ".glb" else None
        _append_animation(document, rig, clip, bin_appender=bin_appender)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        if output_path.suffix.lower() == ".glb":
            _write_glb(document, output_path, bin_chunk=bin_appender.bytes() if bin_appender is not None else None)
        else:
            output_path.write_text(f"{json.dumps(document, indent=2)}\n", encoding="utf-8")
        return output_path


def _read_source_asset(path: Path) -> tuple[dict[str, Any], bytes | None]:
    try:
        if path.suffix.lower() == ".gltf":
            payload = json.loads(path.read_text(encoding="utf-8"))
            bin_chunk = None
        elif path.suffix.lower() == ".glb":
            payload, bin_chunk = _read_glb(path)
        else:
            raise ValueError("unsupported source extension")
    except Exception as exc:
        raise RetargetError(EXPORT_FAILED, f"Could not read source rig document for animation export: {path}") from exc
    if not isinstance(payload, dict) or not isinstance(payload.get("asset"), dict):
        raise RetargetError(EXPORT_FAILED, f"Source rig document is not valid glTF: {path}")
    return payload, bin_chunk


def _append_animation(
    document: dict[str, Any],
    rig: RigInspection,
    clip: RetargetClip,
    *,
    bin_appender: "BinAppender | None" = None,
) -> None:
    nodes = document.get("nodes")
    if not isinstance(nodes, list):
        raise RetargetError(EXPORT_FAILED, "Source rig document has no nodes array.")

    samplers: list[dict[str, Any]] = []
    channels: list[dict[str, Any]] = []
    for channel in clip.channels:
        if channel.path not in {"translation", "rotation"}:
            raise RetargetError(EXPORT_FAILED, f"Unsupported retarget channel path: {channel.path}")
        if not channel.times or len(channel.times) != len(channel.values):
            raise RetargetError(EXPORT_FAILED, "Retarget channel has mismatched time/value samples.")
        target_node = _find_node_index(nodes, channel.target_joint)
        if target_node is None:
            raise RetargetError(EXPORT_FAILED, f"Mapped target joint is missing from glTF nodes: {channel.target_joint}")

        input_accessor = _append_accessor_buffer(
            document,
            _pack_float_scalars(channel.times),
            bin_appender=bin_appender,
            component_type=5126,
            accessor_type="SCALAR",
            count=len(channel.times),
            minimum=[min(channel.times)],
            maximum=[max(channel.times)],
        )
        output_values = _values_in_target_rest_space(nodes[target_node], channel.path, channel.values)
        output_accessor = _append_accessor_buffer(
            document,
            _pack_channel_values(channel.path, output_values),
            bin_appender=bin_appender,
            component_type=5126,
            accessor_type="VEC4" if channel.path == "rotation" else "VEC3",
            count=len(channel.values),
        )
        samplers.append({"input": input_accessor, "output": output_accessor, "interpolation": channel.interpolation})
        channels.append({"sampler": len(samplers) - 1, "target": {"node": target_node, "path": channel.path}})

    animations = document.setdefault("animations", [])
    if not isinstance(animations, list):
        raise RetargetError(EXPORT_FAILED, "Source rig document has a non-list animations field.")
    animations.append({"name": clip.name or GlbAnimationExporter.clip_name, "samplers": samplers, "channels": channels})


def _append_accessor_buffer(
    document: dict[str, Any],
    payload: bytes,
    *,
    bin_appender: "BinAppender | None" = None,
    component_type: int,
    accessor_type: str,
    count: int,
    minimum: list[float] | None = None,
    maximum: list[float] | None = None,
) -> int:
    buffers = document.setdefault("buffers", [])
    buffer_views = document.setdefault("bufferViews", [])
    accessors = document.setdefault("accessors", [])
    if not isinstance(buffers, list) or not isinstance(buffer_views, list) or not isinstance(accessors, list):
        raise RetargetError(EXPORT_FAILED, "Source rig document has invalid buffer/accessor arrays.")

    if bin_appender is None:
        buffer_index = len(buffers)
        byte_offset = 0
        buffers.append({
            "byteLength": len(payload),
            "uri": "data:application/octet-stream;base64," + base64.b64encode(payload).decode("ascii"),
        })
    else:
        buffer_index, byte_offset = bin_appender.append(payload)
    buffer_view_index = len(buffer_views)
    buffer_views.append({"buffer": buffer_index, "byteOffset": byte_offset, "byteLength": len(payload)})
    accessor: dict[str, Any] = {
        "bufferView": buffer_view_index,
        "componentType": component_type,
        "count": count,
        "type": accessor_type,
    }
    if minimum is not None:
        accessor["min"] = minimum
    if maximum is not None:
        accessor["max"] = maximum
    accessors.append(accessor)
    return len(accessors) - 1


class BinAppender:
    """Append animation payloads to a GLB BIN buffer while preserving source bytes."""

    def __init__(self, document: dict[str, Any], bin_chunk: bytes, *, buffer_index: int = 0):
        self.document = document
        self.buffer_index = buffer_index
        self._data = bytearray(bin_chunk)

    def append(self, payload: bytes) -> tuple[int, int]:
        self._pad_to_4()
        byte_offset = len(self._data)
        self._data.extend(payload)
        self._pad_to_4()
        self._update_declared_length()
        return self.buffer_index, byte_offset

    def bytes(self) -> bytes:
        self._pad_to_4()
        self._update_declared_length()
        return bytes(self._data)

    def _pad_to_4(self) -> None:
        padding = (4 - (len(self._data) % 4)) % 4
        if padding:
            self._data.extend(b"\x00" * padding)

    def _update_declared_length(self) -> None:
        buffers = self.document.get("buffers")
        if not isinstance(buffers, list) or self.buffer_index >= len(buffers) or not isinstance(buffers[self.buffer_index], dict):
            raise RetargetError(EXPORT_FAILED, "Source GLB has invalid buffer 0 for animation data.")
        buffers[self.buffer_index]["byteLength"] = len(self._data)


def _source_bin_appender(document: dict[str, Any], source_bin: bytes | None) -> BinAppender | None:
    buffers = document.get("buffers")
    if not isinstance(buffers, list) or not buffers or not isinstance(buffers[0], dict):
        return None
    if buffers[0].get("uri") is not None:
        return None
    if source_bin is None:
        raise RetargetError(EXPORT_FAILED, "Source GLB references buffer 0 BIN storage but has no BIN chunk to preserve.")
    declared = buffers[0].get("byteLength")
    if isinstance(declared, int) and declared > len(source_bin):
        raise RetargetError(EXPORT_FAILED, "Source GLB BIN chunk is shorter than buffers[0].byteLength.")
    return BinAppender(document, source_bin, buffer_index=0)


def _pack_float_scalars(values: tuple[float, ...]) -> bytes:
    return struct.pack(f"<{len(values)}f", *values)


def _pack_vec3_values(values: tuple[tuple[float, ...], ...]) -> bytes:
    flat: list[float] = []
    for value in values:
        if len(value) != 3:
            raise RetargetError(EXPORT_FAILED, "Only VEC3 translation channels are supported.")
        flat.extend(float(component) for component in value)
    return struct.pack(f"<{len(flat)}f", *flat)


def _pack_vec4_values(values: tuple[tuple[float, ...], ...]) -> bytes:
    flat: list[float] = []
    for value in values:
        if len(value) != 4:
            raise RetargetError(EXPORT_FAILED, "Only VEC4 rotation channels are supported.")
        flat.extend(float(component) for component in value)
    return struct.pack(f"<{len(flat)}f", *flat)


def _pack_channel_values(path: str, values: tuple[tuple[float, ...], ...]) -> bytes:
    if path == "translation":
        return _pack_vec3_values(values)
    if path == "rotation":
        return _pack_vec4_values(values)
    raise RetargetError(EXPORT_FAILED, f"Unsupported retarget channel path: {path}")


def _values_in_target_rest_space(
    node: dict[str, Any],
    path: str,
    source_values: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    if not source_values:
        raise RetargetError(EXPORT_FAILED, "Retarget channel contains no output samples.")
    if path == "translation":
        rest = _node_translation(node)
        first = _vec3(source_values[0], "translation")
        return tuple(_add_vec3(rest, _sub_vec3(_vec3(value, "translation"), first)) for value in source_values)
    if path == "rotation":
        rest = _node_rotation(node)
        first_inverse = _inverse_quaternion_xyzw(_normalize_quaternion_xyzw(_vec4(source_values[0], "rotation")))
        adjusted = []
        for value in source_values:
            source = _normalize_quaternion_xyzw(_vec4(value, "rotation"))
            # Assumption: BVH local source samples and target glTF rest samples are both
            # expressed in local joint space, so the source-frame delta composes after
            # the target rest rotation: output = normalize(target_rest * delta).
            delta = _multiply_quaternion_xyzw(source, first_inverse)
            adjusted.append(_normalize_quaternion_xyzw(_multiply_quaternion_xyzw(rest, delta)))
        return tuple(adjusted)
    raise RetargetError(EXPORT_FAILED, f"Unsupported retarget channel path: {path}")


def _node_translation(node: dict[str, Any]) -> tuple[float, float, float]:
    return _vec3(tuple(node.get("translation", (0.0, 0.0, 0.0))), "node translation")


def _node_rotation(node: dict[str, Any]) -> tuple[float, float, float, float]:
    return _normalize_quaternion_xyzw(_vec4(tuple(node.get("rotation", (0.0, 0.0, 0.0, 1.0))), "node rotation"))


def _vec3(value: tuple[float, ...], label: str) -> tuple[float, float, float]:
    if len(value) != 3:
        raise RetargetError(EXPORT_FAILED, f"Expected VEC3 {label} values.")
    return (float(value[0]), float(value[1]), float(value[2]))


def _vec4(value: tuple[float, ...], label: str) -> tuple[float, float, float, float]:
    if len(value) != 4:
        raise RetargetError(EXPORT_FAILED, f"Expected VEC4 {label} values.")
    return (float(value[0]), float(value[1]), float(value[2]), float(value[3]))


def _add_vec3(left: tuple[float, float, float], right: tuple[float, float, float]) -> tuple[float, float, float]:
    return (left[0] + right[0], left[1] + right[1], left[2] + right[2])


def _sub_vec3(left: tuple[float, float, float], right: tuple[float, float, float]) -> tuple[float, float, float]:
    return (left[0] - right[0], left[1] - right[1], left[2] - right[2])


def _multiply_quaternion_xyzw(
    left: tuple[float, float, float, float],
    right: tuple[float, float, float, float],
) -> tuple[float, float, float, float]:
    lx, ly, lz, lw = left
    rx, ry, rz, rw = right
    return (
        lw * rx + lx * rw + ly * rz - lz * ry,
        lw * ry - lx * rz + ly * rw + lz * rx,
        lw * rz + lx * ry - ly * rx + lz * rw,
        lw * rw - lx * rx - ly * ry - lz * rz,
    )


def _inverse_quaternion_xyzw(quaternion: tuple[float, float, float, float]) -> tuple[float, float, float, float]:
    x, y, z, w = quaternion
    length_squared = x * x + y * y + z * z + w * w
    if length_squared <= 0.0:
        return (0.0, 0.0, 0.0, 1.0)
    return (-x / length_squared, -y / length_squared, -z / length_squared, w / length_squared)


def _normalize_quaternion_xyzw(quaternion: tuple[float, float, float, float]) -> tuple[float, float, float, float]:
    length = math.sqrt(sum(component * component for component in quaternion))
    if length <= 0.0:
        return (0.0, 0.0, 0.0, 1.0)
    x, y, z, w = quaternion
    return (x / length, y / length, z / length, w / length)


def _find_node_index(nodes: list[Any], target_joint: str) -> int | None:
    for index, node in enumerate(nodes):
        if isinstance(node, dict) and node.get("name") == target_joint:
            return index
    return None


def _write_glb(document: dict[str, Any], output_path: Path, *, bin_chunk: bytes | None = None) -> None:
    json_chunk = json.dumps(document, separators=(",", ":")).encode("utf-8")
    json_padding = (4 - (len(json_chunk) % 4)) % 4
    json_chunk += b" " * json_padding
    bin_payload = None
    if bin_chunk is not None:
        bin_payload = bin_chunk + (b"\x00" * ((4 - (len(bin_chunk) % 4)) % 4))
    total_length = 12 + 8 + len(json_chunk) + (8 + len(bin_payload) if bin_payload is not None else 0)
    with output_path.open("wb") as handle:
        handle.write(b"glTF")
        handle.write(struct.pack("<II", 2, total_length))
        handle.write(struct.pack("<II", len(json_chunk), 0x4E4F534A))
        handle.write(json_chunk)
        if bin_payload is not None:
            handle.write(struct.pack("<II", len(bin_payload), 0x004E4942))
            handle.write(bin_payload)


def _read_glb(path: Path) -> tuple[dict[str, Any], bytes | None]:
    data = path.read_bytes()
    if len(data) < 20 or data[:4] != b"glTF":
        raise ValueError("invalid GLB header")
    version, length = struct.unpack_from("<II", data, 4)
    if version != 2:
        raise ValueError("only GLB v2 is supported")
    if length != len(data):
        raise ValueError("GLB declared length does not match file length")
    offset = 12
    json_payload: bytes | None = None
    bin_payload: bytes | None = None
    while offset + 8 <= len(data):
        chunk_length, chunk_type = struct.unpack_from("<II", data, offset)
        offset += 8
        if offset + chunk_length > len(data):
            raise ValueError("GLB chunk exceeds file bounds")
        payload = data[offset:offset + chunk_length]
        offset += chunk_length
        if chunk_type == 0x4E4F534A and json_payload is None:
            json_payload = payload.rstrip(b" \t\r\n\x00")
        elif chunk_type == 0x004E4942 and bin_payload is None:
            bin_payload = payload
    if offset != len(data):
        raise ValueError("GLB chunks are not aligned with file length")
    if json_payload is None:
        raise ValueError("GLB JSON chunk is missing")
    return json.loads(json_payload.decode("utf-8")), bin_payload
